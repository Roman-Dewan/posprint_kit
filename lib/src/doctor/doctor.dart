import 'dart:io' show Platform;

import '../core/logger.dart';

/// An individual diagnostic check performed by `EscposLink.doctor()`.
class DoctorCheck {
  const DoctorCheck({
    required this.name,
    required this.passed,
    required this.message,
    this.hint,
  });

  /// The category or feature name being tested (e.g. 'Network Support', 'Bluetooth Permissions').
  final String name;

  /// Whether the check passed successfully.
  final bool passed;

  /// Detailed message explaining current status or findings.
  final String message;

  /// Plain-English troubleshooting instruction if the check failed.
  final String? hint;

  @override
  String toString() {
    final icon = passed ? '✓' : '✗';
    final buffer = StringBuffer('[$icon] $name: $message');
    if (hint != null && hint!.isNotEmpty) {
      buffer.write('\n    Hint: $hint');
    }
    return buffer.toString();
  }
}

/// Aggregated diagnostic report generated by `EscposLink.doctor()`.
class DoctorReport {
  const DoctorReport(this.checks);

  /// All individual diagnostic check results.
  final List<DoctorCheck> checks;

  /// Returns `true` if any diagnostic check failed.
  bool get hasErrors => checks.any((c) => !c.passed);

  @override
  String toString() {
    final buffer = StringBuffer('=== posprint_kit / escpos_link Doctor ===\n');
    for (final check in checks) {
      buffer.writeln(check.toString());
    }
    buffer.writeln(
      hasErrors
          ? '\n! Issues found. Follow the hints above to resolve setup problems.'
          : '\n✓ All basic diagnostics passed! Ready to print.',
    );
    return buffer.toString();
  }
}

/// Diagnostician for POS printing configuration, device reachability, and OS permissions.
class Doctor {
  Doctor._();

  /// Runs environment and capability checks.
  static Future<DoctorReport> check() async {
    final checks = <DoctorCheck>[];

    // 1. Operating system check
    try {
      final os = Platform.operatingSystem;
      checks.add(
        DoctorCheck(
          name: 'Operating System',
          passed: true,
          message: 'Running on $os (${Platform.operatingSystemVersion})',
        ),
      );

      // 2. Network connectivity capabilities
      checks.add(
        const DoctorCheck(
          name: 'WiFi / LAN TCP',
          passed: true,
          message: 'Raw TCP sockets (port 9100) are fully supported.',
        ),
      );

      // 3. Platform transport restrictions
      if (Platform.isIOS) {
        checks.add(
          const DoctorCheck(
            name: 'iOS Transport Capabilities',
            passed: true,
            message: 'WiFi and BLE are supported. (Apple iOS does not permit generic USB or Bluetooth Classic SPP).',
            hint: 'Ensure NSLocalNetworkUsageDescription and NSBluetoothAlwaysUsageDescription are declared in Info.plist.',
          ),
        );
      } else if (Platform.isAndroid) {
        checks.add(
          const DoctorCheck(
            name: 'Android Transport Capabilities',
            passed: true,
            message: 'WiFi, Bluetooth Classic SPP, BLE, and USB OTG are supported.',
            hint: 'For Bluetooth on Android 12+, ensure BLUETOOTH_CONNECT is declared. For USB, add <uses-feature android.hardware.usb.host android:required="false" />.',
          ),
        );
      }
    } catch (e) {
      PosLogger.warning('Platform detection limited in this environment: $e');
      checks.add(
        // OLD: DoctorCheck(
        const DoctorCheck(
          name: 'Platform Environment',
          passed: true,
          message: 'Running in mock or web test environment.',
        ),
      );
    }

    return DoctorReport(checks);
  }
}
